#!/bin/sh
# SPDX-License-Identifier: Apache-2.0
#
# Smoke-tests a production binary: starts it on loopback with a throwaway
# data directory and no music, and checks that
#   - /api/health answers {"status":"ok"} (and the expected version, if given),
#   - "/" serves the real embedded frontend, not the placeholder page,
#   - a hashed JavaScript asset is served with a JavaScript content type,
#   - the PWA files (manifest, offline page, icons, generated sw.js) are
#     served with the right types, and sw.js caches the asset but no /api path,
#   - unknown /api/* paths return JSON 404, not the frontend,
#   - the process stops cleanly on SIGTERM.
#
# Usage: scripts/smoke-test.sh path/to/rewind [expected-version]
#   SMOKE_PORT   loopback port to use (default 18731)
#
# Linux/macOS only (needs curl). Used by CI, release and deploy workflows.
set -eu

bin=${1:?usage: smoke-test.sh BINARY [EXPECTED_VERSION]}
want_version=${2:-}
port=${SMOKE_PORT:-18731}
base="http://127.0.0.1:$port"

work=$(mktemp -d)
log="$work/rewind.log"
pid=""
cleanup() {
	if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then kill -KILL "$pid" 2>/dev/null || true; fi
	rm -rf "$work"
}
trap cleanup EXIT

fail() {
	echo "smoke test FAILED: $*" >&2
	echo "--- server log ---" >&2
	cat "$log" >&2 || true
	exit 1
}

REWIND_ADDR="127.0.0.1:$port" REWIND_DATA_DIR="$work/data" REWIND_LOG_FORMAT=text \
	"$bin" >"$log" 2>&1 &
pid=$!

i=0
until curl -fsS "$base/api/health" -o "$work/health.json" 2>/dev/null; do
	i=$((i + 1))
	[ "$i" -le 100 ] || fail "server did not answer /api/health within 10s"
	kill -0 "$pid" 2>/dev/null || fail "server exited during startup"
	sleep 0.1
done

grep -q '"status":"ok"' "$work/health.json" || fail "unexpected health response: $(cat "$work/health.json")"
if [ -n "$want_version" ]; then
	grep -q "\"version\":\"$want_version\"" "$work/health.json" ||
		fail "health reports $(cat "$work/health.json"), want version $want_version"
fi

curl -fsS "$base/" -o "$work/index.html" || fail "GET / failed"
grep -q '<title>Rewind</title>' "$work/index.html" || fail "GET / did not serve the Rewind frontend"
if grep -q 'frontend is not included in this build' "$work/index.html"; then
	fail "binary serves the placeholder page; it was built without the embedded frontend"
fi

asset=$(grep -o '/assets/[A-Za-z0-9_.-]*\.js' "$work/index.html" | head -n 1)
[ -n "$asset" ] || fail "index.html references no JavaScript asset"
ctype=$(curl -fsS -o /dev/null -w '%{content_type}' "$base$asset") || fail "GET $asset failed"
case "$ctype" in
text/javascript*) ;;
*) fail "GET $asset returned content type '$ctype'" ;;
esac

# PWA files: the service worker is generated by the build and must list the
# hashed asset, and must never list API paths.
check_type() {
	t=$(curl -fsS -o /dev/null -w '%{content_type}' "$base$1") || fail "GET $1 failed"
	case "$t" in
	$2*) ;;
	*) fail "GET $1 returned content type '$t', want $2" ;;
	esac
}
check_type /manifest.webmanifest application/manifest+json
check_type /offline.html text/html
check_type /icons/icon-512.png image/png
check_type /sw.js text/javascript
curl -fsS "$base/sw.js" -o "$work/sw.js" || fail "GET /sw.js failed"
grep -q "\"$asset\"" "$work/sw.js" || fail "sw.js does not cache $asset"
if grep -q '"/api' "$work/sw.js"; then
	fail "sw.js lists an /api path for caching"
fi

code=$(curl -sS -o "$work/notfound.json" -w '%{http_code}' "$base/api/does-not-exist")
[ "$code" = 404 ] || fail "unknown API path returned HTTP $code, want 404"
grep -q '"code":"not_found"' "$work/notfound.json" || fail "unknown API path did not return a JSON error"

kill -TERM "$pid"
status=0
wait "$pid" || status=$?
pid=""
[ "$status" -eq 0 ] || fail "server exited with status $status after SIGTERM"

echo "smoke test passed: $(cat "$work/health.json")"
